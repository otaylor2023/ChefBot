"""Setups: a scene in an environment, attributes we care about, and the named tasks it offers
(setups/<name>.yaml; the pick setups are generated by generate_pick.py). A setup names no robot and no skill.

    setup = setups.load("robocasa_pick/dev_03_banana")
    task = setup.task("pick")

(agentic-skills-exploration's setups/.)
"""

from __future__ import annotations

from dataclasses import dataclass, field
from pathlib import Path

import yaml

from chefbot.autoresearch import tasks

ROOT = Path(__file__).resolve().parent


@dataclass
class Setup:
    name: str
    environment: str  # robocasa
    scene: dict  # {layout, style, seed, objects: [{category, model}, ...]}
    attributes: dict = field(default_factory=dict)
    raw_tasks: dict = field(default_factory=dict)

    @property
    def task_names(self) -> list[str]:
        return list(self.raw_tasks)

    def task(self, name: str) -> tasks.Task:
        if name not in self.raw_tasks:
            raise KeyError(f"setup {self.name} has no task {name!r}; tasks: {', '.join(self.raw_tasks)}")
        entry = self.raw_tasks[name]
        return tasks.get(entry["type"]).bind(name, entry)


def path(name: str) -> Path:
    return ROOT / f"{name}.yaml"


def load(name: str) -> Setup:
    p = path(name)
    if not p.exists():
        raise ValueError(f"no setup {name!r} ({p})")
    raw = yaml.safe_load(p.read_text())
    return Setup(name, raw["environment"], raw["scene"], raw.get("attributes") or {}, raw.get("tasks") or {})


def names(prefix: str = "") -> list[str]:
    return sorted(str(p.relative_to(ROOT).with_suffix("")) for p in ROOT.rglob("*.yaml") if str(p.relative_to(ROOT)).startswith(prefix))
